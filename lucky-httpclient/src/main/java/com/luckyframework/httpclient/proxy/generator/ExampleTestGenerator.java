package com.luckyframework.httpclient.proxy.generator;

/**
 * 生成配套的报文反序列化测试骨架
 * <p>
 * 价值在于：用户拿到真实报文样本后，可以直接在IDE里跑一次这个测试，
 * 立刻验证生成的实体结构与报文是否匹配，而不必手写一遍反序列化样板代码。
 * 生成的测试使用JUnit 4，与本项目测试用例保持一致。
 */
public class ExampleTestGenerator {

    /**
     * 单个Java字符串字面量片段的长度上限，超过则拆成多段拼接，避免生成一行超长代码
     */
    private static final int MAX_LITERAL_SEGMENT_LENGTH = 100;

    private ExampleTestGenerator() {
    }

    /**
     * 生成测试类代码
     *
     * @param packageName 实体所在包名，测试类与之同包以便直接引用实体
     * @param className   实体主类名
     * @param rawBody     报文原始文本
     * @param framework   配置的序列化框架
     * @param xmlBody     报文是否为XML
     * @return 测试类JavaCode
     */
    public static JavaCode generate(String packageName, String className, String rawBody,
                                    SerializationFramework framework, boolean xmlBody) {
        String testClassName = className + "DeserializeTest";
        StringBuilder code = new StringBuilder();

        code.append("package ").append(packageName).append(";\n\n");

        SerializationFramework effective = framework == null ? SerializationFramework.NONE : framework;
        boolean useXml = xmlBody || effective == SerializationFramework.JACKSON_XML
                || effective == SerializationFramework.XSTREAM || effective == SerializationFramework.JAXB;

        appendImports(code, effective, useXml);

        code.append("/**\n");
        code.append(" * Deserialization test skeleton generated by lucky-httpclient.\n");
        code.append(" * The sample below comes from a real response and is used to check whether the\n");
        code.append(" * generated entity matches the payload; assertions are minimal, add your own.\n");
        code.append(" */\n");
        code.append("public class ").append(testClassName).append(" {\n\n");
        code.append("    private static final String SAMPLE = ")
                .append(toJavaLiterals(rawBody))
                .append(";\n\n");
        code.append(buildTestMethod(effective, useXml, className));
        code.append("}\n");

        return JavaCode.of(packageName, testClassName, code.toString());
    }

    /**
     * 输出测试类需要的import
     */
    private static void appendImports(StringBuilder code, SerializationFramework framework, boolean useXml) {
        switch (framework) {
            case GSON:
                code.append("import com.google.gson.Gson;\n");
                break;
            case FASTJSON:
                code.append("import com.alibaba.fastjson.JSON;\n");
                break;
            case FASTJSON2:
                code.append("import com.alibaba.fastjson2.JSON;\n");
                break;
            case JACKSON_XML:
                code.append("import com.fasterxml.jackson.dataformat.xml.XmlMapper;\n");
                break;
            case XSTREAM:
                code.append("import com.thoughtworks.xstream.XStream;\n");
                break;
            case JAXB:
                code.append("import javax.xml.bind.JAXBContext;\n");
                code.append("import java.io.StringReader;\n");
                break;
            case JACKSON:
            case NONE:
            default:
                // XML报文在未配置XML框架时仍按Jackson处理，保持可编译
                if (useXml) {
                    code.append("import com.fasterxml.jackson.dataformat.xml.XmlMapper;\n");
                } else {
                    code.append("import com.fasterxml.jackson.databind.ObjectMapper;\n");
                }
                break;
        }
        code.append("import org.junit.Test;\n\n");
        code.append("import static org.junit.Assert.assertNotNull;\n\n");
    }

    /**
     * 构建反序列化测试方法
     */
    private static String buildTestMethod(SerializationFramework framework, boolean useXml, String className) {
        StringBuilder code = new StringBuilder();
        code.append("    @Test\n");
        code.append("    public void deserializeSample() throws Exception {\n");
        code.append("        ").append(className).append(" entity = ").append(deserializeExpression(framework, useXml, className)).append(";\n");
        code.append("        assertNotNull(entity);\n");
        code.append("        // TODO: add business assertions, e.g. verify the values of key fields\n");
        code.append("    }\n");
        return code.toString();
    }

    /**
     * 按序列化框架拼装对应的反序列化表达式
     */
    private static String deserializeExpression(SerializationFramework framework, boolean useXml, String className) {
        switch (framework) {
            case GSON:
                return "new Gson().fromJson(SAMPLE, " + className + ".class)";
            case FASTJSON:
            case FASTJSON2:
                return "JSON.parseObject(SAMPLE, " + className + ".class)";
            case XSTREAM:
                // XStream默认会把简单类名当节点名，若实体上的@XStreamAlias生效需自行调 processAnnotations
                return "(" + className + ") new XStream().fromXML(SAMPLE)";
            case JAXB:
                return "(" + className + ") JAXBContext.newInstance(" + className + ".class)"
                        + ".createUnmarshaller().unmarshal(new StringReader(SAMPLE))";
            case JACKSON_XML:
                return "new XmlMapper().readValue(SAMPLE, " + className + ".class)";
            case JACKSON:
            case NONE:
            default:
                if (useXml) {
                    return "new XmlMapper().readValue(SAMPLE, " + className + ".class)";
                }
                return "new ObjectMapper().readValue(SAMPLE, " + className + ".class)";
        }
    }

    /**
     * 把报文文本转成Java字符串字面量，过长时拆成多段用 + 连接
     */
    private static String toJavaLiterals(String rawBody) {
        if (rawBody == null || rawBody.isEmpty()) {
            return "\"\"";
        }
        String escaped = escapeLiteral(rawBody);
        StringBuilder sb = new StringBuilder();
        int offset = 0;
        while (offset < escaped.length()) {
            int end = Math.min(offset + MAX_LITERAL_SEGMENT_LENGTH, escaped.length());
            if (offset > 0) {
                sb.append("\n                + ");
            }
            sb.append('"').append(escaped, offset, end).append('"');
            offset = end;
        }
        return sb.toString();
    }

    /**
     * 转义Java字符串字面量中需要转义的字符
     */
    private static String escapeLiteral(String text) {
        StringBuilder sb = new StringBuilder(text.length() + 16);
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '\\':
                    sb.append("\\\\");
                    break;
                case '"':
                    sb.append("\\\"");
                    break;
                case '\n':
                    sb.append("\\n");
                    break;
                case '\r':
                    sb.append("\\r");
                    break;
                case '\t':
                    sb.append("\\t");
                    break;
                default:
                    if (c < 0x20) {
                        // 其余控制字符按Unicode转义，避免写入不可见字符
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
                    break;
            }
        }
        return sb.toString();
    }
}
